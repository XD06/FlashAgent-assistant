/** Render terminal-style output (command / MCP): honour real ANSI colours the
 * program emitted, else apply a restrained leading-status tint. A plain <pre>
 * with coloured <span> runs — no per-field parsing. When pinToBottom is set
 * (live command output) the view sticks to its tail as chunks stream in. */
function TerminalOutput({
  text,
  className,
  pinToBottom,
  variant
}: {
  text: string
  className: string
  pinToBottom?: boolean
  /** 'read' tints only the line-number gutter; default renders ANSI/status. */
  variant?: 'terminal' | 'read'
}) {
  const segments = React.useMemo(
    () => (variant === 'read' ? highlightLineNumbers(text) : renderTerminalText(text)),
    [text, variant]
  )
  const ref = React.useRef<HTMLPreElement | null>(null)
  React.useEffect(() => {
    if (pinToBottom && ref.current) ref.current.scrollTop = ref.current.scrollHeight
  }, [text, pinToBottom])
  return (
    <pre ref={ref} className={className}>
      {segments.map((seg, i) => {
        const style: React.CSSProperties = {}
        if (seg.color) style.color = seg.color
        if (seg.bold) style.fontWeight = 600
        if (seg.dim) style.opacity = 0.6
        if (seg.italic) style.fontStyle = 'italic'
        if (seg.underline) style.textDecoration = 'underline'
        return (
          <span key={i} style={style}>
            {seg.text}
          </span>
        )
      })}
    </pre>
  )
}

/** Render an edit/write as a real unified diff: old lines prefixed with `-`
 * (red), new lines with `+` (green). Makes "what replaced what" obvious
 * instead of two same-looking blocks. write_file has only newText → all `+`. */
function DiffBlock({ oldText, newText }: { oldText?: string; newText?: string }) {
  const rows = React.useMemo(() => {
    const out: { sign: '+' | '-'; text: string }[] = []
    if (oldText !== undefined) {
      for (const line of oldText.replace(/\r\n/g, '\n').replace(/\r/g, '').split('\n')) {
        out.push({ sign: '-', text: line })
      }
    }
    if (newText !== undefined) {
      for (const line of newText.replace(/\r\n/g, '\n').replace(/\r/g, '').split('\n')) {
        out.push({ sign: '+', text: line })
      }
    }
    return out
  }, [oldText, newText])
  return (
    <pre className="agent-tool-row__diff agent-tool-row__diff--unified">
      {rows.map((row, i) => (
        <div
          key={i}
          className={`agent-tool-row__diff-line agent-tool-row__diff-line--${row.sign === '+' ? 'add' : 'del'}`}
        >
          <span className="agent-tool-row__diff-sign">{row.sign}</span>
          <span className="agent-tool-row__diff-text">{row.text}</span>
        </div>
      ))}
    </pre>
  )
}

function AgentToolRow({
  event,
  live,
  isZh,
  onRevert
}: {
  event: AgentToolEvent
  live: boolean
  isZh: boolean
  onRevert: (callId: string) => void
}) {
  const [open, setOpen] = React.useState(false)
  const label = TOOL_LABELS[event.toolName]
  // MCP tools carry a mcp__server__tool name; the summary already shows
  // "server · tool", so a generic MCP badge is enough here.
  const isMcp = event.toolName.startsWith('mcp__')
  const category = TOOL_CATEGORIES[event.toolName] ?? (isMcp ? 'mcp' : 'other')
  const title = label ? (isZh ? label.zh : label.en) : isMcp ? 'MCP' : event.toolName
  const hasDetail = !!(event.oldText || event.newText || event.result)
  const showDetail = open || event.state === 'pending-approval'
  const canRevert = (event.toolName === 'write_file' || event.toolName === 'edit_file') && event.state === 'done'
  const approve = (approved: boolean, alwaysAllow = false) => {
    void window.assistantLite.agent.approveTool(event.callId, approved, alwaysAllow)
  }
  return (
    <div className={`agent-tool-row agent-tool-row--${event.state} agent-tool-row--cat-${category}`}>
      <div
        className="agent-tool-row__head"
        onClick={() => hasDetail && setOpen((v) => !v)}
        style={hasDetail ? { cursor: 'pointer' } : undefined}
      >
        <Icon name={TOOL_ICONS[event.toolName] ?? (isMcp ? 'blocks' : 'pencil')} size={13} />
        <span className="agent-tool-row__name">{title}</span>
        <code className="agent-tool-row__summary" title={event.summary}>{event.summary}</code>
        {canRevert && (
          <button
            className="agent-tool-row__revert"
            title={isZh ? '恢复到本次修改前的内容' : 'Restore the pre-edit content'}
            onClick={(e) => {
              e.stopPropagation()
              onRevert(event.callId)
            }}
          >
            {isZh ? '回退' : 'Revert'}
          </button>
        )}
        <span className="agent-tool-row__state">{stateLabel(event.state, isZh)}</span>
      </div>
      {event.state === 'pending-approval' && live && (
        <div className="agent-tool-row__actions">
          <button className="agent-tool-row__btn agent-tool-row__btn--allow" onClick={() => approve(true)}>
            {isZh ? '允许' : 'Allow'}
          </button>
          <button className="agent-tool-row__btn" onClick={() => approve(true, true)}>
            {isZh ? '始终允许' : 'Always allow'}
          </button>
          <button className="agent-tool-row__btn agent-tool-row__btn--reject" onClick={() => approve(false)}>
            {isZh ? '拒绝' : 'Reject'}
          </button>
        </div>
      )}
      {event.state === 'running' && event.liveOutput && (
        <TerminalOutput
          className="agent-tool-row__result agent-tool-row__result--live"
          text={event.liveOutput}
          pinToBottom
        />
      )}
      {showDetail && hasDetail && (
        <div className="agent-tool-row__detail">
          {(event.oldText !== undefined || event.newText !== undefined) && (
            <DiffBlock oldText={event.oldText} newText={event.newText} />
          )}
          {event.result &&
            // Command/MCP output is terminal-like: parse ANSI (or add a
            // restrained status hint). Reads tint only the line-number gutter.
            // Failures always render red regardless of category.
            (category === 'command' || category === 'mcp' || event.state === 'error' || event.state === 'rejected' ? (
              <TerminalOutput
                className={`agent-tool-row__result agent-tool-row__result--${
                  event.state === 'error' || event.state === 'rejected' ? 'error' : category
                }`}
                text={event.result}
              />
            ) : category === 'read' ? (
              <TerminalOutput
                className={`agent-tool-row__result agent-tool-row__result--${category}`}
                text={event.result}
                variant="read"
              />
            ) : (
              <pre className={`agent-tool-row__result agent-tool-row__result--${category}`}>{event.result}</pre>
            ))}
        </div>
      )}
    </div>
  )
}

/** A run of consecutive tool calls. Stays expanded — which commands ran,
 * what was edited/read is part of the transcript and must remain visible
 * (each row's *output* is what collapses, inside AgentToolRow). The header
 * still toggles manually for users who want the one-line summary. */
function AgentToolGroup({
  events,
  live,
  current,
  isZh,
  onRevert
}: {
  events: AgentToolEvent[]
  live: boolean
  /** True while this is the last block of a still-streaming turn. */
  current: boolean
  isZh: boolean
  onRevert: (callId: string) => void
}) {
  const active = events.some((ev) => ev.state === 'pending-approval' || ev.state === 'running')
  const [manual, setManual] = React.useState<boolean | null>(null)
  // Open by default and after settling — no auto-collapse. Only an explicit
  // header click folds the group to its one-line summary.
  const open = manual ?? true
  const failed = events.filter((ev) => ev.state === 'error' || ev.state === 'rejected').length
  return (
    <div className={`agent-tool-group${open ? ' agent-tool-group--open' : ''}`}>
      <div className="agent-tool-group__header" onClick={() => setManual(!open)}>
        <span className="agent-tool-group__chevron">
          <Icon name="chevron-right" size={12} />
        </span>
        <span className="agent-tool-group__title">
          {isZh ? `${events.length} 个操作` : `${events.length} action${events.length > 1 ? 's' : ''}`}
          {active || (current && live) ? (isZh ? ' · 进行中' : ' · in progress') : ''}
          {failed > 0 ? (isZh ? ` · ${failed} 个失败` : ` · ${failed} failed`) : ''}
        </span>
        {!open && <code className="agent-tool-group__peek">{events[events.length - 1]?.summary}</code>}
      </div>
      {open &&
        events.map((event) => (
          <AgentToolRow key={event.callId} event={event} live={live} isZh={isZh} onRevert={onRevert} />
        ))}
    </div>
  )
}

/** Memoized body of an assistant turn (search status, thinking, text and
 * tool blocks). The streaming setChat updates are immutable and only replace
 * the LAST turn's object identity, so every settled turn bails out here
 * instead of re-walking its whole block tree on each 50ms flush. The props
 * this depends on are render-stable: `t` is memoized in ChatMode and
 * `onRevert` is a useCallback. */
const AssistantTurnBody = React.memo(function AssistantTurnBody({
  turn,
  isZh,
  t,
  onRevert
}: {
  turn: ChatTurn
  isZh: boolean
  t: (key: string) => string
  onRevert: (callId: string) => void
}) {
  return (
    <>
      {turn.searchQuery && (
        <div className={`search-tool-status${turn.searchQuery.startsWith('⚠️') ? ' search-tool-status--error' : ''}`}>
          <Icon name="search" size={13} />
          <span>{turn.searchQuery.startsWith('⚠️')
            ? turn.searchQuery
            : (isZh ? `联网搜索：${turn.searchQuery}` : `Web search: ${turn.searchQuery}`)}</span>
        </div>
      )}
      {turn.reasoning && !turn.blocks?.some((block) => block.kind === 'thinking') && (
        <ThinkingBlock text={turn.reasoning} pending={turn.reasoningPending ?? false} t={t} />
      )}
      {(turn.blocks?.length
        ? turn.blocks
        : turn.text
          ? [{ kind: 'text' as const, text: turn.text }]
          : []
      ).map((block, blockIndex, blockList) => {
        if (block.kind === 'text') {
          // Display path also drops model-imitated tool-record blocks:
          // the real execution blocks are rendered right here, so a
          // hand-written ledger is pure noise (and often confusing).
          const stripped = block.text ? stripForgedRecap(block.text) : ''
          return stripped ? (
            <MarkdownView key={blockIndex} pending={!!turn.pending}>
              {stripped}
            </MarkdownView>
          ) : null
        }
        if (block.kind === 'thinking') {
          return (
            <ThinkingBlock
              key={blockIndex}
              text={block.text}
              pending={!!block.pending && !!turn.pending}
              t={t}
            />
          )
        }
        if (block.kind === 'injected') {
          // Mid-task user note, shown right where the tool loop
          // picked it up — same bubble style as a user message.
          return (
            <div key={blockIndex} className="chat-injected-note">
              <span className="user-msg-injected-tag">
                <Icon name="corner-down-right" size={11} />
                {isZh ? '任务中追加' : 'Added mid-task'}
              </span>
              <div className="chat-injected-note__text">{block.text}</div>
            </div>
          )
        }
        return (
          <AgentToolGroup
            key={blockIndex}
            events={block.events}
            live={!!turn.pending}
            current={!!turn.pending && blockIndex === blockList.length - 1}
            isZh={isZh}
            onRevert={onRevert}
          />
        )
      })}
      {!turn.text && !turn.blocks?.length && turn.pending ? (
        <span className="thinking-indicator">{t('preparing')}</span>
      ) : null}
      {turn.error && <div className="error">{turn.error}</div>}
    </>
  )
})

