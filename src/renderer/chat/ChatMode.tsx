// Cross-turn grounding: assistant turns replay the tool calls that actually
// ran. The send path ships them as a structured toolTrace (expanded into
// native tool-call/tool-result messages at the protocol layer — history
// looks like real tool use, not narration); toolRecap below renders the
// text form, still used when serializing stale turns for the summarizer.
const RECAP_HEADINGS = ['【本轮实际执行的工具调用】', '[Tool calls actually executed this turn]']
const RECAP_ENDINGS = ['【工具记录结束】', '[End of tool record]']

// The model sees the machine-appended recap block in replayed history and
// may imitate it, forging a "tool record" for work it never did. Strip
// look-alike blocks from model-written text so only the authentic recap
// appended below survives in the send path; the display/copy/export paths
// strip them too — a hand-written ledger is fabrication noise (the UI shows
// the real tool blocks already). Authentic blocks end with a
// RECAP_ENDINGS marker; for markerless imitations fall back to skipping the
// heading's list/output lines.
function stripForgedRecap(text: string): string {
  // The machine prepends `[tool: name(args) → ok]` to every real tool result
  // (and the authentic recap below reuses that shape). A genuine `[tool: ...]`
  // line never lives in model-written turn text — it's appended after this
  // strip or sits inside API tool messages — so any such line here is the
  // model imitating the prefix to forge an execution record. Drop them all.
  const hasForgedPrefix = /^\s*\[tool:\s/m.test(text)
  const hasHeading = RECAP_HEADINGS.some((h) => text.includes(h))
  if (!hasForgedPrefix && !hasHeading) return text
  let lines = text.split('\n')
  if (hasForgedPrefix) lines = lines.filter((l) => !/^\s*\[tool:\s/.test(l))
  if (!hasHeading) return lines.join('\n').trimEnd()
  const out: string[] = []
  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trim()
    if (RECAP_HEADINGS.some((h) => trimmed.startsWith(h))) {
      const end = lines.findIndex((l, j) => j > i && RECAP_ENDINGS.some((m) => l.trim().startsWith(m)))
      if (end !== -1) {
        i = end
        continue
      }
      let j = i + 1
      while (j < lines.length) {
        const t = lines[j].trim()
        if (t === '' || t.startsWith('- ') || t.startsWith('✓') || t.startsWith('✗') || lines[j].startsWith('  ')) j++
        else break
      }
      i = j - 1
      continue
    }
    out.push(lines[i])
  }
  return out.join('\n').trimEnd()
}

/** Mid-task user notes stored as blocks inside an assistant turn. */
function injectedNotes(turn: ChatTurn): string[] {
  return (turn.blocks ?? []).flatMap((b) => (b.kind === 'injected' ? [b.text] : []))
}

function toolRecap(turn: ChatTurn, isZh: boolean, withOutput = false): string {
  if (turn.role !== 'assistant' || !turn.blocks) return ''
  const settled = turn.blocks
    .flatMap((b) => (b.kind === 'tools' ? b.events : []))
    .filter((e) => e.state === 'done' || e.state === 'error' || e.state === 'rejected' || e.state === 'reverted')
  if (settled.length === 0) return ''
  const lines = settled.map((e) => {
    const mark = e.state === 'done' ? 'ok' : e.state
    // Same identity shape as the in-loop result prefix (`[tool: … → status]`)
    // so the model sees one canonical, machine-only format everywhere.
    let line = `[tool: ${e.toolName} ${e.summary} → ${mark}]`
    // Recent turns carry the output (already head+tail capped at source),
    // indented two spaces so the markerless strip fallback still recognises
    // the block shape.
    if (withOutput && e.result && (e.state === 'done' || e.state === 'error')) {
      const body = e.result.slice(0, TOOL_TRACE_OUTPUT_PER_CALL)
      const truncated =
        body.length < e.result.length ? (isZh ? '\n  （输出已截断）' : '\n  (output truncated)') : ''
      line += `\n${body.replace(/^/gm, '  ')}${truncated}`
    }
    return line
  })
  return `\n\n${isZh ? RECAP_HEADINGS[0] : RECAP_HEADINGS[1]}\n${lines.join('\n')}\n${isZh ? RECAP_ENDINGS[0] : RECAP_ENDINGS[1]}`
}

/** Settled tool events of an assistant turn, in display order. */
function settledToolEvents(turn: ChatTurn): AgentToolEvent[] {
  if (turn.role !== 'assistant' || !turn.blocks) return []
  return turn.blocks
    .flatMap((b) => (b.kind === 'tools' ? b.events : []))
    .filter((e) => e.state === 'done' || e.state === 'error' || e.state === 'rejected' || e.state === 'reverted')
}

// ---- Compression material sizing ----
/** Hard cap on a single turn's contribution to the summarize material
 * (head 70% + tail 25%; a giant paste must not blow up the request). */
const COMPACT_TURN_MAX_CHARS = 20_000
/** Char budget per summarize batch — keeps each request comfortably inside
 * the compress model's window even with the previous doc attached. */
const COMPACT_BATCH_MAX_CHARS = 48_000
/** Flat token estimate per pasted image (vision inputs aren't char-based). */
const IMAGE_TOKENS_ESTIMATE = 1_000

// Cheap per-turn token estimate for sizing the recent-keep window. Mirrors
// what the send path replays for a turn (text + inlined files + tool recap
// with capped outputs) without building the replay strings. Script-aware
// (CJK tokenizes ~3× denser than the flat chars/4 rule assumed), so each
// text piece is scanned — the WeakMap memoises per turn object, and turns
// are immutable-updated, so re-renders and re-sends only scan changed turns.
const turnTokensCache = new WeakMap<ChatTurn, number>()
function estimateTurnTokens(turn: ChatTurn): number {
  const cached = turnTokensCache.get(turn)
  if (cached !== undefined) return cached
  let tokens = estimateTokensFromText(turn.text ?? '')
  for (const f of turn.files ?? []) {
    tokens += estimateTokensFromText(f.name) + estimateTokensFromText(f.text) + 4
  }
  if (turn.role === 'assistant' && turn.blocks) {
    for (const block of turn.blocks) {
      if (block.kind === 'injected') {
        tokens += estimateTokensFromText(block.text)
        continue
      }
      if (block.kind !== 'tools') continue
      for (const e of block.events) {
        if (e.state !== 'done' && e.state !== 'error' && e.state !== 'rejected' && e.state !== 'reverted') continue
        tokens += estimateTokensFromText(e.summary) + estimateTokensFromChars(e.toolName.length + 16)
        if (e.result && (e.state === 'done' || e.state === 'error')) {
          tokens += estimateTokensFromText(
            e.result.length > TOOL_TRACE_OUTPUT_PER_CALL ? e.result.slice(0, TOOL_TRACE_OUTPUT_PER_CALL) : e.result
          )
        }
      }
    }
  }
  tokens += (turn.images?.length ?? 0) * IMAGE_TOKENS_ESTIMATE
  turnTokensCache.set(turn, tokens)
  return tokens
}

/** Keep full evidence for complete recent user task rounds. The message cap
 * is a transport safety limit, not a normal "keep N turns" policy: it only
 * reserves room for the recap head and the user message being sent. */
function computeChatTaskRoundKeepStart(turns: ChatTurn[], windowTokens: number): number {
  return computeTaskRoundKeepStart(
    turns.map((turn) => ({ role: turn.role, taskRoundId: turn.taskRoundId, tokens: estimateTurnTokens(turn) })),
    windowTokens,
    sendMessageCapForWindow(windowTokens) - 2
  )
}

// Rolling-compression policy (window constants + trigger math) lives in
// ./compaction so the pure logic stays unit-testable. Send-path only — the
