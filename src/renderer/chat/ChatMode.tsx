/** Ordered content of an assistant turn: text, thinking and tool runs
 * interleaved in the order they actually happened. */
type TurnBlock =
  | { kind: 'text'; text: string }
  | { kind: 'thinking'; text: string; pending?: boolean }
  | { kind: 'tools'; events: AgentToolEvent[] }
  /** User note delivered mid-request — rendered at the exact point in the
   * stream where the tool loop picked it up, not above the whole reply. */
  | { kind: 'injected'; text: string }

interface ChatTurn {
  /** Stable render key; absent on turns persisted before ids existed. */
  id?: string
  /** One user task round spans its initiating user turn and assistant work. */
  taskRoundId?: string
  role: 'user' | 'assistant'
  text: string
  /** Legacy single reasoning blob (older saved topics); new turns put
   * thinking blocks into `blocks` so multiple requests stay in order. */
  reasoning?: string
  reasoningPending?: boolean
  pending?: boolean
  error?: string
  searchQuery?: string
  blocks?: TurnBlock[]
  /** User note delivered mid-request into the running tool loop. */
  injected?: boolean
  /** Pasted images (data URLs) — sent as OpenAI-style image_url parts. */
  images?: string[]
  /** Pasted text files — content is inlined into the sent text. */
  files?: FileAttachment[]
  /** Content-free samples emitted before each model request in this user task
   * round. Kept locally for later estimator calibration. */
  contextMeasurements?: Array<ContextMeasurement & { taskRoundId?: string; modelRequestIndex: number }>
}

